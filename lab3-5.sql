    loan_date DATE NOT NULL, --дата выдачи книги, нот нулл..да...нот нул...мой любимый нот нулл...
    return_date DATE NOT NULL, --дата возврата книги, не может быть null, при выдаче сразу указывается дата возврата
    actual_return_date DATE,--дата фактического возврата книги, может быть null если книга не возвращена
    PRIMARY KEY(loan_id), --первичный ключ
    FOREIGN KEY (reader_id) REFERENCES Readers(reader_id) ,--внешний ключ на таблицу "читатели"
    FOREIGN KEY (isbn) REFERENCES books(isbn),--внешний ключ на таблицу "книги", преференсес указывают на конкретное поле
    CHECK (return_date >= loan_date), --возврат не может быть раньше выдачи
    CHECK (actual_return_date IS NULL OR actual_return_date >= loan_date) --по сути, реализация возможности продления срока "аренды" книги
);
