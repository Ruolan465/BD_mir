CREATE TABLE loan --создала таблицу "выдача", дополнительная таблица для отношения многие ко многим между таблицами "книги" и "читатели"
( 
    loan_id SERIAL, --ID сздается автоматически, сериал делает "n+1" при добавлении новой записи
    reader_id INT NOT NULL, --ID читателя,нот нулл что бы поле было обязательно заполненно
